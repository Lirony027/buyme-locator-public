#!/usr/bin/env node
import fs from 'node:fs';

const ROOT = new URL('..', import.meta.url);
const ADDRESSES = new URL('poc/buyme-addresses.json', ROOT);
const CHAINS = new URL('poc/buyme-chains-osm.json', ROOT);
const OUTPUT = new URL('poc/buyme-data.js', ROOT);
const PAGE = new URL('poc/buyme-map-osm.html', ROOT);
const BUYME_ENDPOINT = 'https://buyme.co.il/brands/13438757/options';

const read = (url, label) => {
  if (!fs.existsSync(url)) {
    throw new Error(`Missing ${label}. Run its resolver script first.`);
  }
  return JSON.parse(fs.readFileSync(url, 'utf-8'));
};

const addresses = read(ADDRESSES, 'poc/buyme-addresses.json');
const chains = read(CHAINS, 'poc/buyme-chains-osm.json');

/** BuyMe's own region id for "מימוש אונליין" (online redemption). */
const ONLINE_REGION_ID = 3038;

const res = await fetch(BUYME_ENDPOINT, {
  headers: {
    'User-Agent':
      'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
    Accept: 'application/json, text/plain, */*',
    Referer: 'https://buyme.co.il/brands/13438757',
  },
});
if (!res.ok) throw new Error(`BuyMe request failed: ${res.status} ${res.statusText}`);
const { brands } = await res.json();

/** Refuse to write a bundle from a degraded catalogue fetch. */
const MIN_BRANDS = 500;
if (brands.length < MIN_BRANDS) {
  throw new Error(
    `Only ${brands.length} brands returned (expected at least ${MIN_BRANDS}) — refusing to write a bundle whose coverage caveat would be silently empty`
  );
}

/**
 * Merchants that redeem online and have no physical presence at all. They
 * are carried through rather than dropped: "spendable, but not anywhere in
 * particular" is a true and useful answer.
 *
 * This must stay the exact complement of the chain filter in
 * scripts/resolve-buyme-chains-osm.mjs. Testing `online_redeem` alone put 60
 * brands in both lists — מקדונלד'ס, with 116 mapped branches, was counted as
 * online-only.
 */
const onlineOnly = brands
  .filter(
    (b) =>
      b.online_redeem &&
      !b.googleMapAddr &&
      !(b.supplier_regions ?? []).some((r) => Number(r.region_id) !== ONLINE_REGION_ID)
  )
  .map((b) => b.title)
  .sort((a, b) => a.localeCompare(b, 'he'));

if (onlineOnly.length === 0) {
  throw new Error(
    'No online-only merchants found — region filtering has probably broken (check region_id types)'
  );
}

const locations = [];

for (const brand of addresses.brands) {
  locations.push({
    brand: brand.name,
    lat: brand.lat,
    lng: brand.lng,
    label: brand.address,
    source: 'address',
    precision: brand.precision,
  });
}

for (const brand of chains.brands) {
  for (const location of brand.locations) {
    locations.push({
      brand: brand.name,
      lat: location.lat,
      lng: location.lng,
      label: location.label,
      source: 'osm',
      precision: 'exact',
    });
  }
}

// The page must be able to say how much of the catalogue it could NOT place.
// Without this it would state "757 עסקים" as though that were the catalogue,
// which is the completeness claim the design explicitly forbids.
const placed = new Set(locations.map((l) => l.brand));
const catalogueSize = brands.length;
const unmappedCount = brands.filter(
  (b) => !placed.has(b.title) && !onlineOnly.includes(b.title)
).length;

const payload = JSON.stringify({
  generatedAt: new Date().toISOString(),
  locations,
  onlineOnly,
  catalogueSize,
  unmappedCount,
});

// `</script>` inside a string would close the host <script> element early and
// break the page. JSON.stringify does not escape `<`, so do it here. The
// escapes are still valid JSON string syntax, so JSON.parse is unaffected.
const scriptSafe = payload.replace(/</g, '\\u003c').replace(/>/g, '\\u003e');

// Written for anyone serving poc/ over HTTP, and as a diffable artefact.
fs.writeFileSync(
  OUTPUT,
  '// Generated by scripts/build-poc-data.mjs — do not edit.\n' +
    `window.BUYME_DATA = ${payload};\n`
);

// The page is opened by double-clicking it, and browsers refuse to load a
// local <script src> subresource from a file:// document — verified: the map
// rendered but every count read zero. Inlining the data removes the
// subresource entirely, so there is nothing left for the browser to block.
// Only the marked block is rewritten; the rest of the page is hand-edited.
const START = '/* BUYME_DATA_START */';
const END = '/* BUYME_DATA_END */';

let html = fs.readFileSync(PAGE, 'utf-8');
const startAt = html.indexOf(START);
const endAt = html.indexOf(END);
if (startAt === -1 || endAt === -1 || endAt < startAt) {
  throw new Error(
    `Could not find the ${START} / ${END} markers in poc/buyme-map-osm.html — the page must keep them so the data can be injected.`
  );
}

html =
  html.slice(0, startAt + START.length) +
  `\nwindow.BUYME_DATA = ${scriptSafe};\n` +
  html.slice(endAt);
fs.writeFileSync(PAGE, html);

console.log(
  `Wrote ${locations.length} locations across ${placed.size} brands, plus ${onlineOnly.length} online-only merchants ` +
    `(catalogue: ${catalogueSize}, unmapped: ${unmappedCount})\n` +
    `  -> poc/buyme-data.js (for HTTP serving)\n` +
    `  -> inlined into poc/buyme-map-osm.html (so file:// works)`
);
